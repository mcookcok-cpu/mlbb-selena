import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome';
const b = await chromium.launch({ executablePath: exe, headless: true, args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 412, height: 860 } });
const errs = []; p.on('pageerror', e => errs.push('PAGEERR ' + e.message.slice(0, 200)));
p.on('console', m => { if (['error', 'warning'].includes(m.type())) errs.push(m.type().toUpperCase() + ' ' + m.text().slice(0, 200)); });
await p.goto('http://localhost:2600/'); await p.waitForFunction(() => document.querySelector('#loading')?.classList.contains('done'), null, { timeout: 150000 });
await p.waitForTimeout(1200);
const clipsNow = () => p.evaluate(() => [...document.querySelectorAll('#body [data-clip]')].map(b => b.dataset.clip).filter(n => n.startsWith('orig_')));
await p.evaluate(() => document.querySelectorAll('#tabs .chip')[0].click()); await p.waitForTimeout(500);
console.log('1) default (tanpa ?exp): klip orig =', JSON.stringify(await clipsNow()));
await p.evaluate(() => { const r = [...document.querySelectorAll('#body .row')].find(r => r.textContent.includes('Eksperimental')); r.querySelector('input').click(); });
await p.waitForTimeout(1200);
console.log('2) toggle ON: klip orig =', JSON.stringify(await clipsNow()));
await p.evaluate(() => document.querySelector('#body [data-clip="orig_run"]').click()); await p.waitForTimeout(1500);
console.log('3) tombol orig_run aktif:', await p.evaluate(() => document.querySelector('#body [data-clip="orig_run"]').classList.contains('on')));
await p.screenshot({ path: '/tmp/exp_run.png' });
await p.evaluate(() => { const r = [...document.querySelectorAll('#body .row')].find(r => r.textContent.includes('Eksperimental')); r.querySelector('input').click(); });
await p.waitForTimeout(1200);
console.log('4) toggle OFF: klip orig =', JSON.stringify(await clipsNow()), '| idle aktif:', await p.evaluate(() => document.querySelector('#body [data-clip="city_idle"]')?.classList.contains('on')));
console.log('ERRORS/WARN', errs.length ? errs : 'tidak ada');
await b.close();

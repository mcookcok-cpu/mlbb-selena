import { chromium } from 'playwright-core';
import fs from 'fs';
const base = 'http://100.106.213.94:6171';
const exe = (fs.readdirSync(process.env.HOME + '/.cache/ms-playwright').filter(d => d.startsWith('chromium')).map(d => d))[0];
console.log('chromium dir:', exe);
const b = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome', headless: true, args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 420, height: 860 } });
const errs = [], failed = [];
p.on('console', m => { if (['error','warning'].includes(m.type())) errs.push(m.type() + ': ' + m.text().slice(0, 160)); });
p.on('pageerror', e => errs.push('pageerror: ' + String(e).slice(0, 160)));
p.on('requestfailed', r => failed.push(r.url().slice(0, 120)));
const r = await p.goto(base + '/', { waitUntil: 'networkidle', timeout: 30000 });
console.log('status akhir:', r.status(), 'url:', p.url());
console.log('judul:', await p.title());
console.log('input:', await p.$$eval('input', els => els.map(e => e.type + ':' + (e.name || e.placeholder || ''))));
console.log('tombol:', await p.$$eval('button', els => els.map(e => e.innerText.trim().slice(0, 30))));
await p.screenshot({ path: '/tmp/kana_login.png' });
console.log('ERR:', errs.length ? errs : 'tidak ada');
console.log('REQUEST GAGAL:', failed.length ? failed : 'tidak ada');
await b.close();
